#!/usr/bin/env python3
"""make_specs.py: first-round level 175 specs for the third classes, from ../balance.json.

For each third class in the sidegrade spec: its transcendent class's runs at level 99; each of its
runs that was compared with the transcendent class at 99, 130, 150 and 175 (single target: aim 1.35
to 1.65 at 175); each of its area runs that was compared with one of its own, at 175 (aim: at most
0.55 of that run). Writes <class>.json beside this file; a spec that exists is left alone (it has
been tuned by hand since).
"""
import json, re

# The classes of the expanded-classes mod; the others are transcendent-third-classes.
EXPANDED = {"kagerou_oboro", "rebellion", "star_emperor", "soul_reaper", "super_novice"}
from pathlib import Path
HERE = Path(__file__).resolve().parent
NAMES = {4061: "warlock", 4062: "ranger", 4063: "arch_bishop", 4064: "mechanic", 4065: "guillotine_cross", 4073: "royal_guard",
         4074: "sorcerer", 4075: "minstrel", 4076: "wanderer", 4077: "sura", 4078: "genetic", 4079: "shadow_chaser"}
src = json.loads((HERE.parent / "balance.json").read_text())
runs = {r["id"]: r for r in src["runs"]}
KEEP = ("class", "weapon", "ammo", "left", "stats", "user", "skills", "levels", "how", "pre", "extra", "cartload", "count",
        "charge", "method", "step", "seq")
for job, name in NAMES.items():
    out, done = [], set()
    def ref(rid):   # a transcendent run, at level 99
        if rid not in done:
            done.add(rid)
            out.append({"id": rid, **{k: v for k, v in runs[rid].items() if k in KEEP}, "level": 99})
    mine = [r for r in src["runs"] if r["class"] == job]
    for r in mine:
        v = runs.get(r.get("versus", ""))
        if v is not None and v["class"] != job:
            ref(v["id"])
    for r in mine:
        v = runs.get(r.get("versus", ""))
        body = {k: x for k, x in r.items() if k in KEEP}
        area = "_area" in r["id"]
        if v is None or v["class"] != job:   # compared with the transcendent class
            for lv in ((175,) if area else (99, 130, 150, 175)):
                run = {"id": f"L{lv}_{r['id']}", **body, "level": lv}
                if v is not None:
                    run["versus"] = v["id"]
                    if lv == 175 and not area:
                        run["aim"] = [1.35, 1.65]
                out.append(run)
        else:                                 # an area skill, compared with one of its own
            out.append({"id": f"L175_{r['id']}", **body, "level": 175, "versus": f"L175_{v['id']}", "aim": [0.0, 0.55]})
    path = HERE / f"{name}.json"
    if path.exists():
        print("kept ", path.name); continue
    path.write_text(json.dumps({
        "_about": f"Level 175, first round: {name.replace('_', ' ')} against its transcendent class on the anchor. Generated by make_specs.py from ../balance.json; see README.md for the method and the targets.",
        "load": ["mods/level175-core", "mods/expanded-classes" if name in EXPANDED else "mods/transcendent-third-classes"], "seconds": 30,
        "defaults": {"dummy": "anchor", "repeat": 3, "median": True}, "runs": out}, indent=1) + "\n")
    print("wrote", path.name, len(out), "runs")
