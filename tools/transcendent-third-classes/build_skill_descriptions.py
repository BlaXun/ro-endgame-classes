#!/usr/bin/env python3
"""Write each class mod's skill descriptions: the entries the client lacks for its skills.

    python3 tools/transcendent-third-classes/build_skill_descriptions.py            # rewrite them
    python3 tools/transcendent-third-classes/build_skill_descriptions.py --check    # fail if stale

The client reads skill descriptions from one table. A mod ships only its own entries in a file of
the same name, and the app merges them into the client's table by skill (docs/MODDING.md), so the
two class mods (transcendent-third-classes and expanded-classes) each ship the entries of the
skills in their own skill tree, taken from skill_descriptions/*.lua (STYLE.md says how an entry is
written). Every skill in a mod's tree must end up with a description, from ROenglishRE's
Pre-Renewal table (the pinned vendor/ROenglishRE, or --translation) or from the mod's entries; the
build fails otherwise. The app needs to be one that merges the table: an older one would let the
mod's file replace the client's whole table.
"""
import argparse
import os
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
# the ragnarokoffline.app checkout, for its translation in vendor/ROenglishRE
APP = Path(os.environ.get("RO_APP") or ROOT.parent / "ragnarokoffline.app")
MODS = ("transcendent-third-classes", "expanded-classes")
SOURCES = HERE / "skill_descriptions"
TABLE = "data/luafiles514/lua files/skillinfoz/skilldescript.lub"
STR = r'"(?:[^"\\\r\n]|\\.)*"'
# an entry over several lines, or the translation's name-only one on a line of its own
ENTRY = re.compile(r'\t\[SKID\.(\w+)\] = \{(?:\r?\n(?:\t\t%s,?\r?\n)+\t\}| %s \}),?' % (STR, STR))
HEAD = ("-- Generated by tools/transcendent-third-classes/build_skill_descriptions.py from\n"
        "-- skill_descriptions/*.lua -- do not hand-edit. Only this mod's skills: the app merges them\n"
        "-- into the client's skill description table by skill.\n")


def entries(text, where):
    """{skill: entry text without the trailing comma} of a skill_descriptions/ file, in its order."""
    out = {}
    for m in ENTRY.finditer(text):
        if m[1] in out:
            sys.exit(f"{where}: {m[1]} twice")
        out[m[1]] = m[0].rstrip(",").replace("\r\n", "\n")
    return out


def check_entry(name, body, where):
    lines = re.findall(r'"((?:[^"\\]|\\.)*)"', body)
    if len(lines) < 3 or not lines[1].startswith("Max Level:"):
        sys.exit(f"{where}: {name}: a name, then 'Max Level: N', then the rest")
    for l in lines:
        if not l.isascii():
            sys.exit(f"{where}: {name}: not plain ASCII: {l}")
        for tag in ("b", "i"):
            if l.count(f"<{tag}>") != l.count(f"</{tag}>"):
                sys.exit(f"{where}: {name}: <{tag}> not closed on its line: {l}")


def find_entry(text, skill):
    """(start, end) of a skill's entry in the table, its trailing comma left out; None if absent."""
    m = re.search(r"\[SKID\.%s\]\s*=\s*\{" % re.escape(skill), text)
    if not m:
        return None
    i, depth, in_str = m.end(), 1, False
    while depth:
        c = text[i]
        if in_str:
            if c == "\\":
                i += 1
            elif c == '"':
                in_str = False
        elif c == '"':
            in_str = True
        elif c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
        i += 1
    return m.start(), i


def sources():
    ours = {}
    for f in sorted(SOURCES.glob("*.lua")):
        src = f.read_text(encoding="utf-8")
        found = entries(src, f.name)
        if len(found) != src.count("[SKID."):
            sys.exit(f"{f.name}: an entry is not written in the expected shape (STYLE.md)")
        for k, v in found.items():
            if k in ours:
                sys.exit(f"{f.name}: {k} is in another file too")
            check_entry(k, v, f.name)
            ours[k] = v
    return ours


def build(translation, allow_missing=False):
    """{mod: file bytes} with each mod's own entries, and how many entries each has."""
    base = (translation / "Translation/Pre-Renewal" / TABLE).read_text(encoding="latin-1").replace("\r\n", "\n")
    ours = sources()
    used, out = set(), {}

    # a name alone is no description (the translation has that for most third-class skills)
    def described(n, mine):
        if n in mine:
            return True
        at = find_entry(base, n)
        return at and len(re.findall(STR, base[at[0]:at[1]])) >= 3

    for mod in MODS:
        tree = set(re.findall(r"- Name: (\w+)", (ROOT / "mods" / mod / "db/skill_tree.yml").read_text(encoding="utf-8")))
        mine = {k: v for k, v in ours.items() if k in tree}
        used |= set(mine)
        missing = sorted(n for n in tree if not described(n, mine))
        if missing and not allow_missing:
            sys.exit(f"{mod}: no description for {len(missing)} skills of the tree: {' '.join(missing)}")
        if missing:
            print(f"{mod}: still without a description: {len(missing)}: {' '.join(missing)}")
        text = HEAD + "SKILL_DESCRIPT = {\n" + ",\n".join("\t" + v.strip() for v in mine.values()) + "\n}\n"
        # the translation's own line ends, so the file reads like the table it adds to
        out[mod] = (text.replace("\n", "\r\n").encode("latin-1"), len(mine))
    unused = sorted(set(ours) - used)
    if unused:
        sys.exit(f"skill_descriptions/: no mod's tree has {' '.join(unused)}")
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--translation", type=Path, default=APP / "vendor/ROenglishRE")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--sources", action="store_true", help="only check skill_descriptions/*.lua and list what is still missing; write nothing")
    a = ap.parse_args()
    built = build(a.translation, allow_missing=a.sources)
    if a.sources:
        print(f"skill_descriptions/: {sum(n for _, n in built.values())} entries, all well-formed")
        return
    stale = []
    for mod, (data, n) in built.items():
        path = ROOT / "mods" / mod / TABLE
        if a.check:
            if not path.exists() or path.read_bytes() != data:
                stale.append(str(path.relative_to(ROOT)))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        print(f"wrote {path.relative_to(ROOT)}: {n} entries")
    if stale:
        sys.exit("stale: " + ", ".join(stale) + " -- run build_skill_descriptions.py")
    if a.check:
        print("up to date")


if __name__ == "__main__":
    main()
